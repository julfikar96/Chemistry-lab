// =========================================================================
// EVALUATION ENGINE CORE FUNCTION
// =========================================================================
export function evaluateReactionEngine(
  currentChemicalIds: string[],
  condition: ReactionCondition = 'RT'
): ReactionEvaluationResult {
  const uniqueIds = Array.from(new Set(currentChemicalIds.map((id) => id.toLowerCase().trim()))).filter(Boolean);

  // If less than 1 chemical, no reaction possible
  if (uniqueIds.length === 0) {
    return {
      isReacting: false,
      reaction: null,
      reasonIfNoReaction: 'No chemical ingredients added।',
      scientificExplanationBangla: 'Select the chemical element in the beaker to start the reaction।',
      reactionTypes: [],
      balancedEquation: '',
      wordEquationBangla: '',
      thermalType: 'THERMONEUTRAL',
      temperatureDelta: 0,
      finalPH: 7.0,
      observations: [],
      explanation: '',
    };
  }

  const chemicals = uniqueIds.map((id) => getChemicalById(id)).filter(Boolean) as Chemical[];

  // Single chemical case: Check for Decomposition / Thermal Decomposition / Electrolysis
  if (uniqueIds.length === 1) {
    const singleId = uniqueIds[0];
    const matchingDecomp = VERIFIED_REACTIONS.find(
      (r) => r.reactants.length === 1 && r.reactants[0].toLowerCase() === singleId
    );

    if (matchingDecomp) {
      // Check required condition (e.g. HEAT or ELECTRICITY)
      if (matchingDecomp.requiredCondition && matchingDecomp.requiredCondition !== condition) {
        let conditionName = 'Heat (Heat Δ)';
        if (matchingDecomp.requiredCondition === 'ELECTRICITY') conditionName = 'Electricity';
        if (matchingDecomp.requiredCondition === 'CATALYST') conditionName = 'catalyst (MnO₂ Catalyst)';

        return {
          isReacting: false,
          reaction: null,
          reasonIfNoReaction: `To activate this dissociation reaction '${conditionName}' condition required।`,
          scientificExplanationBangla: `${chemicals[0]?.banglaName} Stable at normal room temperature। To subtract it from the above terms '${conditionName}' Activate।`,
          reactionTypes: matchingDecomp.reactionTypes,
          balancedEquation: matchingDecomp.balancedEquation,
          wordEquationBangla: matchingDecomp.wordEquationBangla || matchingDecomp.equation,
          thermalType: matchingDecomp.thermalType,
          temperatureDelta: 0,
          finalPH: chemicals[0]?.pH ?? 7.0,
          observations: [`No visible change occurs at room temperature। to initiate the reaction '${conditionName}' apply।`],
          explanation: matchingDecomp.explanation,
        };
      }

      // Condition met!
      return {
        isReacting: true,
        reaction: matchingDecomp,
        reactionTypes: matchingDecomp.reactionTypes,
        balancedEquation: matchingDecomp.balancedEquation,
        wordEquationBangla: matchingDecomp.wordEquationBangla || matchingDecomp.equation,
        netIonicEquation: matchingDecomp.netIonicEquation,
        drivingForce: matchingDecomp.drivingForce,
        thermalType: matchingDecomp.thermalType,
        temperatureDelta: matchingDecomp.temperatureDelta ?? 0,
        finalPH: matchingDecomp.finalPH ?? 7.0,
        precipitate: matchingDecomp.precipitate,
        gas: matchingDecomp.gas,
        colorChange: matchingDecomp.colorChange,
        observations: matchingDecomp.observations,
        explanation: matchingDecomp.explanation,
        microscopicExplanation: matchingDecomp.microscopicExplanation,
        safetyGuidelines: matchingDecomp.safetyGuidelines,
        nctbChapter: matchingDecomp.nctbChapter,
      };
    }

    // No single decomposition defined
    return {
      isReacting: false,
      reaction: null,
      reasonIfNoReaction: 'There is no chemical change in a single component।',
      scientificExplanationBangla: `${chemicals[0]?.banglaName || singleId} Stable under normal conditions। Add another chemical element to cause the reaction।`,
      reactionTypes: [],
      balancedEquation: chemicals[0]?.formula || singleId,
      wordEquationBangla: chemicals[0]?.banglaName || singleId,
      thermalType: 'THERMONEUTRAL',
      temperatureDelta: 0,
      finalPH: chemicals[0]?.pH ?? 7.0,
      observations: [`${chemicals[0]?.banglaName || singleId} stored in beaker।`],
      explanation: `${chemicals[0]?.banglaDescription || ''}`,
    };
  }

  // Multi-chemical case: Look for exact or subset match in VERIFIED_REACTIONS
  // Sort candidates by match length descending (prefer exact matches)
  const matches = VERIFIED_REACTIONS.filter((r) => {
    return r.reactants.every((reqId) => uniqueIds.includes(reqId.toLowerCase()));
  }).sort((a, b) => b.reactants.length - a.reactants.length);

  if (matches.length > 0) {
    const reaction = matches[0];

    // Check condition requirements
    if (reaction.requiredCondition && reaction.requiredCondition !== condition) {
      let condLabel = 'Heat (Heat Δ)';
      if (reaction.requiredCondition === 'ELECTRICITY') condLabel = 'Electricity';
      return {
        isReacting: false,
        reaction: null,
        reasonIfNoReaction: `to complete this reaction '${condLabel}' condition required।`,
        scientificExplanationBangla: `Selected elements do not react readily at normal temperatures। to initiate the reaction '${condLabel}' Activate।`,
        reactionTypes: reaction.reactionTypes,
        balancedEquation: reaction.balancedEquation,
        wordEquationBangla: reaction.wordEquationBangla || reaction.equation,
        thermalType: reaction.thermalType,
        temperatureDelta: 0,
        finalPH: (chemicals.reduce((acc, c) => acc + c.pH, 0) / chemicals.length) || 7.0,
        observations: [`The ingredients are mixed in the beaker। to initiate the reaction '${condLabel}' Click the button।`],
        explanation: reaction.explanation,
      };
    }

    return {
      isReacting: true,
      reaction,
      reactionTypes: reaction.reactionTypes,
      balancedEquation: reaction.balancedEquation,
      wordEquationBangla: reaction.wordEquationBangla || reaction.equation,
      netIonicEquation: reaction.netIonicEquation,
      drivingForce: reaction.drivingForce,
      thermalType: reaction.thermalType,
      temperatureDelta: reaction.temperatureDelta ?? 0,
      finalPH: reaction.finalPH ?? 7.0,
      precipitate: reaction.precipitate,
      gas: reaction.gas,
      colorChange: reaction.colorChange,
      observations: reaction.observations,
      explanation: reaction.explanation,
      microscopicExplanation: reaction.microscopicExplanation,
      safetyGuidelines: reaction.safetyGuidelines,
      nctbChapter: reaction.nctbChapter,
    };
  }

  // =========================================================================
  // DYNAMIC RULE-BASED CHEMICAL INTELLIGENCE ENGINE
  // (Analyzes properties, Reactivity Series, Solubility, Acid-Base rules)
  // =========================================================================

  // 1. Metal Displacement Reactivity Series Rule Check
  const metal = chemicals.find((c) => c.category === 'Metal');
  const salt = chemicals.find((c) => c.category === 'Salt');
  const acid = chemicals.find((c) => c.category === 'Acid');

  if (metal && salt) {
    const metalRank = METAL_REACTIVITY_SERIES[metal.id]?.rank ?? 99;
    // Extract salt cation
    const saltCationId = salt.ions?.cation ? salt.ions.cation.replace(/[^A-Za-z]/g, '').toLowerCase() : '';
    const saltMetalRank = METAL_REACTIVITY_SERIES[saltCationId]?.rank ?? 99;

    if (metalRank > saltMetalRank && saltMetalRank < 99) {
      // Inactive displacement: Metal is LESS reactive than the salt metal!
      return {
        isReacting: false,
        reaction: null,
        reasonIfNoReaction: `No reaction occurs (activation series limitation).।`,
        scientificExplanationBangla: `In the activation series ${metal.banglaName} metal ${salt.banglaName}-is less reactive than its cations (Reactivity Series: ${metal.formula} < ${salt.ions?.cation})। Hence it cannot replace the cation।`,
        reactionTypes: ['SINGLE_DISPLACEMENT'],
        balancedEquation: `${metal.formula} + ${salt.formula} → No Reaction`,
        wordEquationBangla: `${metal.banglaName} + ${salt.banglaName} → No reaction occurs`,
        thermalType: 'THERMONEUTRAL',
        temperatureDelta: 0,
        finalPH: salt.pH,
        observations: [
          'There is no color change in the solution।',
          'No coating or bubbles are formed on the surface of the metal।',
        ],
        explanation: 'According to the reactivity series rule, only the more active metal can displace that metal from the salt solution of the less active metal। No reverse reaction occurs।',
      };
    }
  }

  if (metal && acid) {
    const metalRank = METAL_REACTIVITY_SERIES[metal.id]?.rank ?? 99;
    const hydrogenRank = METAL_REACTIVITY_SERIES['h'].rank; // 9

    if (metalRank > hydrogenRank) {
      // Metal is less reactive than Hydrogen (e.g. Cu, Ag, Au with HCl or dil H2SO4)
      return {
        isReacting: false,
        reaction: null,
        reasonIfNoReaction: `No reaction takes place (metal is under hydrogen)।`,
        scientificExplanationBangla: `In the activation series ${metal.banglaName} Metal lies below hydrogen (${metal.formula} < H₂)। So it is a weak acid (${acid.banglaName}) Unable to replace hydrogen gas from।`,
        reactionTypes: ['ACID_METAL', 'SINGLE_DISPLACEMENT'],
        balancedEquation: `${metal.formula} + ${acid.formula} → No Reaction`,
        wordEquationBangla: `${metal.banglaName} + ${acid.banglaName} → No reaction occurs`,
        thermalType: 'THERMONEUTRAL',
        temperatureDelta: 0,
        finalPH: acid.pH,
        observations: [
          'No bubbles or hydrogen gas evolution is observed in the acid।',
          'The metal part remains unchanged।',
        ],
        explanation: 'Inert metals below hydrogen (copper, silver, gold) are common weak acids to H⁺ Ions cannot oxidize।',
      };
    }
  }

  // 2. Generic Acid + Base Neutralization Fallback
  const anyAcid = chemicals.find((c) => c.category === 'Acid');
  const anyBase = chemicals.find((c) => c.category === 'Base');

  if (anyAcid && anyBase) {
    const tempDelta = anyAcid.pH < 2 && anyBase.pH > 12 ? 2.8 : 1.5;
    const estPH = 7.0;

    return {
      isReacting: true,
      reaction: null,
      reactionTypes: ['NEUTRALIZATION', 'DOUBLE_DISPLACEMENT'],
      balancedEquation: `${anyAcid.formula} + ${anyBase.formula} → Salt (Salt) + H₂O(l)`,
      wordEquationBangla: `${anyAcid.banglaName} + ${anyBase.banglaName} → Salt + water`,
      netIonicEquation: 'H⁺(aq) + OH⁻(aq) → H₂O(l)',
      drivingForce: 'Water (H₂O) structure',
      thermalType: 'EXOTHERMIC',
      temperatureDelta: tempDelta,
      finalPH: estPH,
      observations: [
        `Acids and bases neutralize each other to the pH neutralization range of the solution (~${estPH.toFixed(1)}) gets closer।`,
        `Temp + as a result of mitigation heat emission${tempDelta.toFixed(1)}°C increases।`,
      ],
      explanation: `${anyAcid.banglaName} And ${anyBase.banglaName} Its reduction reaction produces salt and water।`,
    };
  }

  // 3. Same category / Non-reacting general mixture
  const avgPH = chemicals.reduce((sum, c) => sum + c.pH, 0) / chemicals.length;
  const names = chemicals.map((c) => c.banglaName).join(' And ');

  return {
    isReacting: false,
    reaction: null,
    reasonIfNoReaction: 'No chemical reaction takes place in the mixture (physical mixture).।',
    scientificExplanationBangla: `${names} No driving force (eg: precipitation, outgassing, mitigation or redox) is present to form or break new chemical bonds when mixed.। Elements exist as independent ions/molecules in solution।`,
    reactionTypes: [],
    balancedEquation: `${chemicals.map((c) => c.formula).join(' + ')} → There is no chemical change`,
    wordEquationBangla: `${names} → physical mixture`,
    thermalType: 'THERMONEUTRAL',
    temperatureDelta: 0,
    finalPH: Number(avgPH.toFixed(1)),
    observations: [
      'The elements are held together as a simple physical mixture।',
      'No visible precipitation, gas or thermal changes were observed।',
    ],
    explanation: 'For a chemical reaction to occur, there must be a driving force for ion exchange, electron transfer, or the formation of stable compounds (precipitates/gases/waters).।',
  };
}
